-- ──────────────────────────────────────
-- 4. DYNAMIC TABLES (ELT materialization)
-- ──────────────────────────────────────
CREATE OR REPLACE DYNAMIC TABLE DT_DAILY_AIRLINE_PERFORMANCE
    TARGET_LAG = '1 hour'
    WAREHOUSE  = ETL_WH
AS
SELECT
    d.FULL_DATE,
    d.YEAR,
    d.MONTH_NUM,
    d.MONTH_NAME,
    a.AIRLINE_CODE,
    a.AIRLINE_NAME,
    COUNT(*)                                          AS TOTAL_FLIGHTS,
    SUM(IFF(IS_CANCELLED, 1, 0))                      AS CANCELLED,
    SUM(IFF(ARR_DELAY_MIN > 15 AND NOT IS_CANCELLED, 1, 0)) AS DELAYED,
    ROUND(AVG(ARR_DELAY_MIN), 2)                      AS AVG_ARR_DELAY,
    ROUND(AVG(DEP_DELAY_MIN), 2)                      AS AVG_DEP_DELAY,
    ROUND(SUM(TOTAL_REVENUE), 2)                      AS TOTAL_REVENUE,
    ROUND(AVG(LOAD_FACTOR), 4)                        AS AVG_LOAD_FACTOR,
    ROUND(100.0 * SUM(IFF(ARR_DELAY_MIN <= 15 AND NOT IS_CANCELLED, 1, 0))
              / NULLIF(COUNT(*), 0), 2)               AS ON_TIME_PCT
FROM FACT_FLIGHT  F
JOIN DIM_DATE     D ON F.DATE_KEY    = D.DATE_KEY
JOIN DIM_AIRLINE  A ON F.AIRLINE_KEY = A.AIRLINE_KEY
GROUP BY 1,2,3,4,5,6;


-- ──────────────────────────────────────
-- 5. SEMI-STRUCTURED DATA (VARIANT)
-- ──────────────────────────────────────
-- Store raw JSON flight events in Snowflake VARIANT column
CREATE OR REPLACE TABLE RAW_FLIGHT_EVENTS (
    EVENT_ID        STRING       NOT NULL,
    EVENT_TS        TIMESTAMP_NTZ NOT NULL,
    SOURCE_SYSTEM   STRING,
    PAYLOAD         VARIANT,      -- Raw JSON blob
    LOADED_AT       TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

-- Flatten VARIANT for analysis
CREATE OR REPLACE VIEW VW_FLIGHT_EVENTS_FLAT AS
SELECT
    EVENT_ID,
    EVENT_TS,
    PAYLOAD:flightNumber::STRING    AS FLIGHT_NUMBER,
    PAYLOAD:airline::STRING         AS AIRLINE_CODE,
    PAYLOAD:origin::STRING          AS ORIGIN,
    PAYLOAD:destination::STRING     AS DESTINATION,
    PAYLOAD:status::STRING          AS STATUS,
    PAYLOAD:delays.carrier::INT     AS CARRIER_DELAY,
    PAYLOAD:delays.weather::INT     AS WEATHER_DELAY,
    PAYLOAD:delays.nas::INT         AS NAS_DELAY,
    PAYLOAD:position.lat::FLOAT     AS LATITUDE,
    PAYLOAD:position.lon::FLOAT     AS LONGITUDE,
    PAYLOAD:position.altitude::INT  AS ALTITUDE_FT,
    -- Explode nested passenger array
    VALUE:passengerId::STRING       AS PASSENGER_ID,
    VALUE:cabin::STRING             AS CABIN_CLASS
FROM RAW_FLIGHT_EVENTS,
     LATERAL FLATTEN(INPUT => PAYLOAD:passengers) p;


