-- ──────────────────────────────────────
-- 8. DATA MASKING (Column-Level Security)
-- ──────────────────────────────────────

-- PII masking policy for passenger email
CREATE OR REPLACE MASKING POLICY MASK_EMAIL AS (VAL STRING)
RETURNS STRING ->
    CASE
        WHEN CURRENT_ROLE() IN ('AIRLINE_ADMIN', 'DATA_STEWARD') THEN VAL
        WHEN CURRENT_ROLE() = 'AIRLINE_ANALYST'
            THEN REGEXP_REPLACE(VAL, '(.{2})(.+)(@.+)', '\\1****\\3')  -- jo****@email.com
        ELSE '***MASKED***'
    END;

CREATE OR REPLACE MASKING POLICY MASK_PHONE AS (VAL STRING)
RETURNS STRING ->
    CASE
        WHEN CURRENT_ROLE() IN ('AIRLINE_ADMIN', 'DATA_STEWARD') THEN VAL
        ELSE CONCAT('***-***-', RIGHT(VAL, 4))
    END;

CREATE OR REPLACE MASKING POLICY MASK_DOB AS (VAL DATE)
RETURNS DATE ->
    CASE
        WHEN CURRENT_ROLE() IN ('AIRLINE_ADMIN', 'DATA_STEWARD') THEN VAL
        ELSE DATE_TRUNC('YEAR', VAL)   -- Only show birth year
    END;

-- Apply masking policies
ALTER TABLE DIM_PASSENGER MODIFY COLUMN EMAIL  SET MASKING POLICY MASK_EMAIL;
ALTER TABLE DIM_PASSENGER MODIFY COLUMN PHONE  SET MASKING POLICY MASK_PHONE;
ALTER TABLE DIM_PASSENGER MODIFY COLUMN DOB    SET MASKING POLICY MASK_DOB;

-- Ticket/price masking for reader role
CREATE OR REPLACE MASKING POLICY MASK_FARE AS (VAL NUMBER)
RETURNS NUMBER ->
    CASE
        WHEN CURRENT_ROLE() IN ('AIRLINE_ADMIN', 'AIRLINE_ANALYST') THEN VAL
        ELSE NULL
    END;

ALTER TABLE FACT_RESERVATION MODIFY COLUMN TOTAL_FARE SET MASKING POLICY MASK_FARE;


-- ──────────────────────────────────────
-- 9. ROW ACCESS POLICIES (Row-Level Security)
-- ──────────────────────────────────────

-- Analysts only see data for their assigned airline(s)
CREATE OR REPLACE TABLE USER_AIRLINE_ACCESS (
    USERNAME        STRING,
    AIRLINE_CODE    STRING
);

CREATE OR REPLACE ROW ACCESS POLICY RAP_AIRLINE_FILTER
AS (AIRLINE_CODE STRING) RETURNS BOOLEAN ->
    CURRENT_ROLE() IN ('AIRLINE_ADMIN', 'ETL_ROLE')  -- Admins see all
    OR EXISTS (
        SELECT 1 FROM USER_AIRLINE_ACCESS
        WHERE USERNAME    = CURRENT_USER()
          AND AIRLINE_CODE = AIRLINE_CODE
    );

ALTER TABLE FACT_FLIGHT
    ADD ROW ACCESS POLICY RAP_AIRLINE_FILTER ON (AIRLINE_KEY);


